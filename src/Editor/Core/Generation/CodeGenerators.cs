    /// <summary>Builds C# source text with consistent indentation and LF line endings.</summary>
    public sealed class CodeWriter
    {
        private readonly StringBuilder _builder = new();
        private int _indent;

        public CodeWriter Line(string text = "")
        {
            if (text.Length > 0)
            {
                _builder.Append(' ', _indent * 4).Append(text);
            }

            _builder.Append('\n');
            return this;
        }

        public CodeWriter Open(string text = "")
        {
            if (text.Length > 0)
            {
                Line(text);
            }

            Line("{");
            _indent++;
            return this;
        }

        public CodeWriter Close(string suffix = "")
        {
            _indent--;
            return Line("}" + suffix);
        }

        public CodeWriter Summary(string text)
        {
            if (text.Length == 0)
            {
                return this;
            }

            string[] lines = text.Replace("\r\n", "\n").Split('\n');
            if (lines.Length == 1)
            {
                return Line($"/// <summary>{Escape(lines[0])}</summary>");
            }

            Line("/// <summary>");
            foreach (string line in lines)
            {
                Line("/// " + Escape(line));
            }

            return Line("/// </summary>");
        }

        public override string ToString() => _builder.ToString();

        private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
    }

    public sealed record CodegenOptions(string Namespace, string TablesClass, ITableCodec Codec, string ManifestFileName, string? PublicKey);

    internal static class Code
    {
        /// <summary>First lines of every generated file. The committer recognizes its own files by <see cref="Marker"/>.</summary>
        public const string Marker = "Generated by HolySheet";

        public static CodeWriter Begin(string source, IEnumerable<string> usings, string @namespace)
        {
            var writer = new CodeWriter();
            writer.Line("// <auto-generated>");
            writer.Line($"//     {Marker}. Do not edit: the next build overwrites this file.");
            writer.Line("//     To change it, edit the sheet and build again.");
            writer.Line($"//     Source: {source}");
            writer.Line("// </auto-generated>");
            writer.Line("#nullable enable");
            writer.Line("#pragma warning disable CS0169, CS0414, CS0649, CS1591, IDE0044, IDE0051");
            writer.Line();
            foreach (string item in usings)
            {
                writer.Line($"using {item};");
            }

            writer.Line();
            writer.Open($"namespace {@namespace}");
            return writer;
        }

        public static string StringLiteral(string value)
        {
            var builder = new StringBuilder(value.Length + 2).Append('"');
            foreach (char c in value)
            {
                builder.Append(c switch
                {
                    '"' => "\\\"",
                    '\\' => "\\\\",
                    '\n' => "\\n",
                    '\r' => "\\r",
                    '\t' => "\\t",
                    _ => c.ToString()
                });
            }

            return builder.Append('"').ToString();
        }

        /// <summary>The private field that stores a column: "Price" is kept in "_price".</summary>
        public static string StorageName(string field) => "_" + char.ToLowerInvariant(field[0]) + field[1..];

        /// <summary>A camelCase parameter name that cannot be a keyword.</summary>
        public static string ParameterName(string field, params string[] locals)
        {
            string name = char.ToLowerInvariant(field[0]) + field[1..];
            return "@" + (locals.Contains(name, StringComparer.Ordinal) ? name + "Value" : name);
        }
    }

    /// <summary>
    /// Generates a table's row class. Every stored value is a private field that only the serializer writes;
    /// the public surface is get-only properties, so code holding a row has no way to change it.
    /// Arrays are handed out as <c>ReadOnlyArray&lt;T&gt;</c>, which exposes no setter and no mutable span.
    /// </summary>
    public static class RowCodeGenerator
    {
        public static string Generate(TableSchema schema, CodegenOptions options)
        {
            ITableCodec codec = options.Codec;
            CodeWriter writer = Code.Begin(schema.Location, new[] { "System" }.Concat(codec.Usings), options.Namespace);
            writer.Summary($"One row of the {schema.Name} table. Immutable: there is no way to change a row after it is loaded.");
            writer.Line(codec.RowAttribute);
            writer.Open($"public sealed partial class {schema.RowTypeName}");

            var usedNames = new HashSet<string>(schema.Columns.Select(column => column.Field), StringComparer.Ordinal);
            var storageNames = new Dictionary<string, string>(StringComparer.Ordinal);
            int order = 0;
            foreach (ColumnSchema column in schema.Columns)
            {
                ColumnType type = column.Type;
                string storage = Code.StorageName(column.Field);
                bool hasPresenceFlag = type is { Kind: ColumnKind.Reference, IsOptional: true };
                while (usedNames.Contains(storage) || (hasPresenceFlag && usedNames.Contains(storage + "__has")))
                {
                    storage += "_";
                }
                usedNames.Add(storage);
                if (hasPresenceFlag) usedNames.Add(storage + "__has");
                storageNames.Add(column.Field, storage);
                string valueType = type.CSharpValueType;
                if (type.IsArray)
                {
                    writer.Line($"{codec.FieldAttribute(order++)} private {valueType}[] {storage} = global::System.Array.Empty<{valueType}>();");
                }
                else
                {
                    if (hasPresenceFlag)
                    {
                        writer.Line($"{codec.FieldAttribute(order++)} private bool {storage}__has;");
                    }

                    string initializer = valueType == "string" ? " = \"\"" : "";
                    writer.Line($"{codec.FieldAttribute(order++)} private {valueType} {storage}{initializer};");
                }
            }

            writer.Line();
            writer.Line(codec.ConstructorAttribute);
            writer.Open($"private {schema.RowTypeName}()").Close();

            foreach (ColumnSchema column in schema.Columns)
            {
                ColumnType type = column.Type;
                string storage = storageNames[column.Field];
                writer.Line();
                writer.Summary(Describe(column));
                string ignore = codec.IgnoreAttribute;
                if (type.IsArray)
                {
                    writer.Line($"{ignore} public global::HolySheet.ReadOnlyArray<{type.CSharpValueType}> {column.Field} => new global::HolySheet.ReadOnlyArray<{type.CSharpValueType}>({storage});");
                }
                else if (type.Kind == ColumnKind.Reference)
                {
                    string has = type.IsOptional ? storage + "__has" : "true";
                    writer.Line($"{ignore} public {type.TargetTable}Ref {column.Field} => new {type.TargetTable}Ref({has}, {storage});");
                }
                else
                {
                    writer.Line($"{ignore} public {type.CSharpValueType} {column.Field} => {storage};");
                }
            }

            writer.Line();
            string identity = schema.PrimaryKey is { } key ? $" + {storageNames[key.Field]} + " : " + ";
            writer.Line(schema.PrimaryKey != null
                ? $"public override string ToString() => \"{schema.Name}(\"{identity}\")\";"
                : $"public override string ToString() => \"{schema.Name} row\";");
            writer.Close();
            writer.Close();
            return writer.ToString();
        }

        private static string Describe(ColumnSchema column)
        {
            ColumnType type = column.Type;
            string comment = column.Comment;
            if (type.Kind == ColumnKind.Reference)
            {
                string note = type.IsArray ? $"Keys of rows in the {type.TargetTable} table." : $"Points at a row of the {type.TargetTable} table.";
                return comment.Length == 0 ? note : comment + "\n" + note;
            }

            return comment;
        }
    }

    /// <summary>Generates a table class: the rows in sheet order plus a lookup for every key and index column.</summary>
    public static class TableCodeGenerator
    {
        public static string Generate(TableSchema schema, CodegenOptions options)
        {
            ITableCodec codec = options.Codec;
            string row = schema.RowTypeName;
            string table = schema.TableTypeName;
            CodeWriter writer = Code.Begin(schema.Location, new[] { "System", "System.Collections.Generic" }.Concat(codec.Usings), options.Namespace);
            writer.Summary($"The {schema.Name} table. Immutable: a reload produces a new table instead of changing this one.");
            writer.Open($"public sealed partial class {table} : global::HolySheet.ITable");
            writer.Line($"public const string TableName = {Code.StringLiteral(schema.Name)};");
            writer.Line();
            writer.Summary("Hash of the layout this class was generated for. The loader refuses data built for another layout.");
            writer.Line($"public const string SchemaHash = {Code.StringLiteral(schema.Hash)};");
            writer.Line();
            writer.Line($"private readonly {row}[] _rows;");
            foreach (ColumnSchema key in schema.Keys)
            {
                writer.Line($"private readonly Dictionary<{key.Type.CSharpValueType}, {row}> _by{key.Field};");
            }

            foreach (ColumnSchema index in schema.Indexes)
            {
                writer.Line($"private readonly Dictionary<{index.Type.CSharpValueType}, {row}[]> _listBy{index.Field};");
            }

            writer.Line();
            writer.Line("public string Name => TableName;");
            writer.Line();
            writer.Line("public int Count => _rows.Length;");
            writer.Line();
            writer.Summary("The manifest entry this table was loaded from.");
            writer.Line("public global::HolySheet.TableManifestEntry Entry { get; }");
            writer.Line();
            writer.Summary("Every row, in sheet order.");
            writer.Line($"public global::HolySheet.ReadOnlyArray<{row}> Rows => new global::HolySheet.ReadOnlyArray<{row}>(_rows);");

            if (schema.Kind == TableKind.Config)
            {
                writer.Line();
                writer.Summary("The single row of this config table.");
                writer.Line($"public {row} Value => _rows[0];");
            }

            WriteConstructor(writer, schema);

            ColumnSchema? primary = schema.PrimaryKey;
            foreach (ColumnSchema key in schema.Keys)
            {
                WriteKeyLookup(writer, schema, key, ReferenceEquals(key, primary));
            }

            if (primary != null)
            {
                WriteReferenceLookup(writer, schema, primary);
            }

            foreach (ColumnSchema index in schema.Indexes)
            {
                writer.Line();
                string parameter = Code.ParameterName(index.Field, "rows");
                writer.Summary($"Every row whose {index.Field} is the given value, in sheet order. Empty when there is none.");
                writer.Open($"public global::HolySheet.ReadOnlyArray<{row}> ListBy{index.Field}({index.Type.CSharpValueType} {parameter})");
                writer.Line($"return _listBy{index.Field}.TryGetValue({parameter}, out {row}[]? rows) ? new global::HolySheet.ReadOnlyArray<{row}>(rows) : global::HolySheet.ReadOnlyArray<{row}>.Empty;");
                writer.Close();
            }

            writer.Line();
            writer.Summary("Called at the end of the constructor. Implement it in another file of this partial class to build extra lookups.");
            writer.Line("partial void OnLoaded();");
            writer.Line();
            writer.Open("internal static global::HolySheet.ITable Decode(byte[] data, global::HolySheet.TableManifestEntry entry)");
            writer.Line($"{row}[]? rows = {codec.DeserializeExpression(row, "data")};");
            writer.Line($"return new {table}(rows ?? Array.Empty<{row}>(), entry);");
            writer.Close();
            writer.Close();

            if (primary != null)
            {
                WriteRefStruct(writer, schema, primary);
            }

            writer.Close();
            return writer.ToString();
        }

        private static void WriteConstructor(CodeWriter writer, TableSchema schema)
        {
            string row = schema.RowTypeName;
            writer.Line();
            writer.Open($"private {schema.TableTypeName}({row}[] rows, global::HolySheet.TableManifestEntry entry)");
            writer.Line("_rows = rows;");
            writer.Line("Entry = entry;");
            foreach (ColumnSchema key in schema.Keys)
            {
                string comparer = key.Type.CSharpValueType == "string" ? ", StringComparer.Ordinal" : "";
                writer.Line($"_by{key.Field} = new Dictionary<{key.Type.CSharpValueType}, {row}>(rows.Length{comparer});");
            }

            if (schema.Keys.Count > 0)
            {
                writer.Open("for (int index = 0; index < rows.Length; index++)");
                foreach (ColumnSchema key in schema.Keys)
                {
                    // The tool rejects duplicate keys, so one here means the data was not produced by the tool.
                    writer.Open($"if (_by{key.Field}.ContainsKey(rows[index].{key.Field}))");
                    writer.Line($"throw new global::HolySheet.TableLoadException(global::HolySheet.TableLoadError.DecodeFailed, \"The table '{schema.Name}' has two rows with the same {key.Field}: '\" + rows[index].{key.Field} + \"'.\", TableName);");
                    writer.Close();
                    writer.Line();
                    writer.Line($"_by{key.Field}.Add(rows[index].{key.Field}, rows[index]);");
                }

                writer.Close();
            }

            foreach (ColumnSchema index in schema.Indexes)
            {
                string type = index.Type.CSharpValueType;
                string comparer = type == "string" ? "StringComparer.Ordinal" : "";
                writer.Line();
                writer.Line($"var groupsBy{index.Field} = new Dictionary<{type}, List<{row}>>({comparer});");
                writer.Open("for (int index = 0; index < rows.Length; index++)");
                writer.Open($"if (!groupsBy{index.Field}.TryGetValue(rows[index].{index.Field}, out List<{row}>? group))");
                writer.Line($"group = new List<{row}>();");
                writer.Line($"groupsBy{index.Field}.Add(rows[index].{index.Field}, group);");
                writer.Close();
                writer.Line();
                writer.Line("group.Add(rows[index]);");
                writer.Close();
                writer.Line();
                writer.Line($"_listBy{index.Field} = new Dictionary<{type}, {row}[]>(groupsBy{index.Field}.Count{(comparer.Length > 0 ? ", " + comparer : "")});");
                writer.Open($"foreach (KeyValuePair<{type}, List<{row}>> pair in groupsBy{index.Field})");
                writer.Line($"_listBy{index.Field}.Add(pair.Key, pair.Value.ToArray());");
                writer.Close();
            }

            writer.Line();
            writer.Line("OnLoaded();");
            writer.Close();
        }

        private static void WriteKeyLookup(CodeWriter writer, TableSchema schema, ColumnSchema key, bool isPrimary)
        {
            string row = schema.RowTypeName;
            string type = key.Type.CSharpValueType;
            string parameter = Code.ParameterName(key.Field, "row", "found");
            string suffix = isPrimary ? "" : "By" + key.Field;
            string map = "_by" + key.Field;

            if (isPrimary)
            {
                writer.Line();
                writer.Summary($"The row with this {key.Field}. Throws when there is none.");
                writer.Line($"public {row} this[{type} {parameter}] => Get({parameter});");
            }

            writer.Line();
            writer.Summary($"The row with this {key.Field}. Throws when there is none.");
            writer.Open($"public {row} Get{suffix}({type} {parameter})");
            writer.Open($"if ({map}.TryGetValue({parameter}, out {row}? row))");
            writer.Line("return row;");
            writer.Close();
            writer.Line();
            writer.Line($"throw new KeyNotFoundException(\"The table '{schema.Name}' has no row whose {key.Field} is '\" + {parameter} + \"'.\");");
            writer.Close();

            writer.Line();
            writer.Summary($"The row with this {key.Field}, or null when there is none.");
            writer.Open($"public {row}? Find{suffix}({type} {parameter})");
            writer.Line($"return {map}.TryGetValue({parameter}, out {row}? row) ? row : null;");
            writer.Close();

            writer.Line();
            writer.Open($"public bool TryGet{suffix}({type} {parameter}, out {row} row)");
            writer.Open($"if ({map}.TryGetValue({parameter}, out {row}? found))");
            writer.Line("row = found;");
            writer.Line("return true;");
            writer.Close();
            writer.Line();
            writer.Line("row = null!;");
            writer.Line("return false;");
            writer.Close();

            writer.Line();
            writer.Open($"public bool Contains{suffix}({type} {parameter})");
            writer.Line($"return {map}.ContainsKey({parameter});");
            writer.Close();
        }

        private static void WriteReferenceLookup(CodeWriter writer, TableSchema schema, ColumnSchema primary)
        {
            string row = schema.RowTypeName;
            string reference = schema.RefTypeName;
            writer.Line();
            writer.Summary("The row a reference points at. Throws when the reference points at nothing.");
            writer.Open($"public {row} Get({reference} reference)");
            writer.Open("if (!reference.HasValue)");
            writer.Line($"throw new InvalidOperationException(\"The reference to the table '{schema.Name}' points at no row.\");");
            writer.Close();
            writer.Line();
            writer.Line("return Get(reference.Key);");
            writer.Close();

            writer.Line();
            writer.Summary("The row a reference points at, or null when it points at nothing.");
            writer.Open($"public {row}? Find({reference} reference)");
            writer.Line("return reference.HasValue ? Find(reference.Key) : null;");
            writer.Close();

            writer.Line();
            writer.Open($"public bool TryGet({reference} reference, out {row} row)");
            writer.Open("if (reference.HasValue)");
            writer.Line("return TryGet(reference.Key, out row);");
            writer.Close();
            writer.Line();
            writer.Line("row = null!;");
            writer.Line("return false;");
            writer.Close();
        }

        private static void WriteRefStruct(CodeWriter writer, TableSchema schema, ColumnSchema primary)
        {
            string reference = schema.RefTypeName;
            string type = primary.Type.CSharpValueType;
            string equality = type == "string" ? "string.Equals(Key, other.Key, StringComparison.Ordinal)" : "Key.Equals(other.Key)";
            string hash = type == "string" ? "(Key == null ? 0 : Key.GetHashCode())" : "Key.GetHashCode()";
            writer.Line();
            writer.Summary($"Points at a row of the {schema.Name} table by its {primary.Field}, or at nothing. Resolve it with {schema.TableTypeName}.Get.");
            writer.Open($"public readonly struct {reference} : IEquatable<{reference}>");
            writer.Line("public bool HasValue { get; }");
            writer.Line();
            writer.Summary($"The {primary.Field} of the row pointed at. Meaningless when HasValue is false.");
            writer.Line($"public {type} Key {{ get; }}");
            writer.Line();
            writer.Open($"public {reference}(bool hasValue, {type} key)");
            writer.Line("HasValue = hasValue;");
            writer.Line("Key = key;");
            writer.Close();
            writer.Line();
            writer.Line($"public bool Equals({reference} other) => HasValue == other.HasValue && (!HasValue || {equality});");
            writer.Line();
            writer.Line($"public override bool Equals(object? obj) => obj is {reference} other && Equals(other);");
            writer.Line();
            writer.Line($"public override int GetHashCode() => HasValue ? {hash} : 0;");
            writer.Line();
            writer.Line($"public override string ToString() => HasValue ? \"{schema.Name}(\" + Key + \")\" : \"{schema.Name}(none)\";");
            writer.Close();
        }
    }

    public static class EnumCodeGenerator
    {
        public const string FileName = "Enums.g.cs";

        public static string Generate(IReadOnlyList<EnumDefinition> enums, CodegenOptions options)
        {
            CodeWriter writer = Code.Begin("Enums sheets and Mapping<...> columns", new[] { "System" }, options.Namespace);
            for (int index = 0; index < enums.Count; index++)
            {
                EnumDefinition definition = enums[index];
                if (index > 0)
                {
                    writer.Line();
                }

                writer.Summary(definition.Comment);
                if (definition.IsFlags)
                {
                    writer.Line("[Flags]");
                }

                writer.Open($"public enum {definition.Name} : {Scalars.CSharpName(definition.Underlying)}");
                foreach (EnumMember member in definition.Members)
                {
                    string value = definition.Underlying == ScalarKind.ULong
                        ? unchecked((ulong)member.Value).ToString(CultureInfo.InvariantCulture)
                        : member.Value.ToString(CultureInfo.InvariantCulture);
                    writer.Line($"{member.Name} = {value},");
                }

                writer.Close();
            }

            writer.Close();
            return writer.ToString();
        }
    }

    /// <summary>Generates the class that holds every table and knows how to load, reload and watch them.</summary>
    public static class TablesCodeGenerator
    {
        /// <summary>Member names of the generated class. A table with one of these names would collide with them.</summary>
        public static readonly IReadOnlyCollection<string> ReservedNames = new HashSet<string>(StringComparer.Ordinal)
        {
            "SchemaHash", "Serializer", "ManifestFileName", "PublicKey", "Definition", "Manifest", "Tables", "LoadedTables",
            "Load", "LoadAsync", "Reload", "Watch", "_tables"
        };

        public static string Generate(IReadOnlyList<TableSchema> schemas, string schemaHash, CodegenOptions options)
        {
            string name = options.TablesClass;
            CodeWriter writer = Code.Begin("all tables", new[] { "System", "System.Collections.Generic", "System.Threading", "System.Threading.Tasks" }, options.Namespace);
            writer.Summary("Every table, loaded together as one immutable snapshot.\nLoading again never changes a snapshot: it returns a new one, and tables whose data did not change are shared between the two.");
            writer.Open($"public sealed partial class {name} : global::HolySheet.ITableSet");
            writer.Summary("Hash of every table layout and enum this code was generated from. Data built for anything else is refused.");
            writer.Line($"public const string SchemaHash = {Code.StringLiteral(schemaHash)};");
            writer.Line();
            writer.Line($"public const string Serializer = {Code.StringLiteral(options.Codec.Name)};");
            writer.Line();
            writer.Line($"public const string ManifestFileName = {Code.StringLiteral(options.ManifestFileName)};");
            writer.Line();
            writer.Summary("Public key the manifest signature is checked against, or null when the tables are not signed.");
            writer.Line($"public const string? PublicKey = {(string.IsNullOrEmpty(options.PublicKey) ? "null" : Code.StringLiteral(options.PublicKey!))};");
            writer.Line();
            writer.Line("public static global::HolySheet.TableSetDefinition Definition { get; } = new global::HolySheet.TableSetDefinition(Serializer, SchemaHash, ManifestFileName, PublicKey, new global::HolySheet.TableDefinition[]");
            writer.Open();
            foreach (TableSchema schema in schemas)
            {
                writer.Line($"new global::HolySheet.TableDefinition({schema.TableTypeName}.TableName, {schema.TableTypeName}.SchemaHash, {schema.TableTypeName}.Decode),");
            }

            writer.Close(");");
            writer.Line();
            writer.Line("private readonly global::HolySheet.ITable[] _tables;");
            writer.Line();
            writer.Summary("The manifest this snapshot was loaded from. Manifest.Content identifies the exact data.");
            writer.Line("public global::HolySheet.TableManifest Manifest { get; }");
            writer.Line();
            writer.Line("public IReadOnlyList<global::HolySheet.ITable> Tables => _tables;");
            writer.Line();
            writer.Summary("Names of the tables decoded for this snapshot. After a reload, the tables not listed are the same objects as before.");
            writer.Line("public IReadOnlyList<string> LoadedTables { get; }");
            foreach (TableSchema schema in schemas)
            {
                writer.Line();
                writer.Line($"public {schema.TableTypeName} {schema.Name} {{ get; }}");
            }

            writer.Line();
            writer.Open($"private {name}(global::HolySheet.TableSetData data)");
            writer.Line("Manifest = data.Manifest;");
            writer.Line("LoadedTables = data.LoadedTables;");
            writer.Line("_tables = data.Tables.ToArray();");
            for (int index = 0; index < schemas.Count; index++)
            {
                string property = schemas[index].Name == "data" ? "this.data" : schemas[index].Name;
                writer.Line($"{property} = ({schemas[index].TableTypeName})_tables[{index}];");
            }

            writer.Close();

            writer.Line();
            writer.Summary("Loads every table. Throws TableLoadException, and returns nothing, when any file is missing, modified or built for different code.");
            writer.Open($"public static {name} Load(global::HolySheet.TableSource source, global::HolySheet.TableLoadOptions? options = null)");
            writer.Line($"return new {name}(global::HolySheet.TableLoader.Load(Definition, source, options));");
            writer.Close();
            writer.Line();
            writer.Summary("Loads every table from a directory on disk.");
            writer.Open($"public static {name} Load(string directory, global::HolySheet.TableLoadOptions? options = null)");
            writer.Line("return Load(global::HolySheet.TableSource.FromDirectory(directory), options);");
            writer.Close();
            writer.Line();
            writer.Summary("Loads every table without blocking on I/O. Use it where files cannot be read synchronously (Android and WebGL StreamingAssets).");
            writer.Open($"public static async ValueTask<{name}> LoadAsync(global::HolySheet.TableSource source, global::HolySheet.TableLoadOptions? options = null, CancellationToken cancellationToken = default)");
            writer.Line($"return new {name}(await global::HolySheet.TableLoader.LoadAsync(Definition, source, options, null, cancellationToken).ConfigureAwait(false));");
            writer.Close();
            writer.Line();
            writer.Summary("Loads the data again and returns a new snapshot. Tables whose data hash is unchanged are carried over, not decoded again.\nThis snapshot stays valid and unchanged.");
            writer.Open($"public {name} Reload(global::HolySheet.TableSource source, global::HolySheet.TableLoadOptions? options = null)");
            writer.Line($"return new {name}(global::HolySheet.TableLoader.Load(Definition, source, options, this));");
            writer.Close();
            writer.Line();
            writer.Summary("Loads the tables from a directory and keeps them up to date as the files change.\nRead watcher.Current for the latest snapshot; subscribe to watcher.Reloaded to react to changes. Dispose it to stop watching.");
            writer.Open($"public static global::HolySheet.TableWatcher<{name}> Watch(string directory, global::HolySheet.TableWatchOptions? options = null)");
            writer.Line($"return new global::HolySheet.TableWatcher<{name}>(directory, ManifestFileName,");
            writer.Line("    (source, loadOptions, previous) => previous == null ? Load(source, loadOptions) : previous.Reload(source, loadOptions), options);");
            writer.Close();
            writer.Close();
            writer.Close();
            return writer.ToString();
        }
    }
